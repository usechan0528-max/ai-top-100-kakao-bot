// Compile the reviewed source table only; do not infer holidays from the OS calendar.
import fs from 'node:fs';
const root = new URL('../', import.meta.url);
const cells = JSON.parse(fs.readFileSync(new URL('docs/sources/business-calendar/cells.json', root), 'utf8'));
const manifest = JSON.parse(fs.readFileSync(new URL('docs/sources/business-calendar/manifest.json', root), 'utf8'));
const rows = new Map();
for (const c of cells.filter(c => c.sheet === '8. 날짜별 영업·출고 달력')) {
  const [, col, n] = /^([A-Z]+)(\d+)$/.exec(c.cell);
  if (+n < 6 || !'ABCD'.includes(col)) continue;
  if (!rows.has(+n)) rows.set(+n, {});
  rows.get(+n)[col] = c.value;
}
const data = [...rows].sort((a,b)=>a[0]-b[0]).map(([n,r]) => {
  if (!r.A || !r.B || !['영업','휴무'].includes(r.C) || !['출고일','출고 없음'].includes(r.D)) throw Error(`Invalid source row ${n}`);
  return [r.A,r.B,r.C === '영업',r.D === '출고일'];
});
if (data.length !== 305) throw Error('Incomplete calendar');
const sha = manifest.files.find(f=>f.name.endsWith('.xlsx')).sha256;
fs.writeFileSync(new URL('src/business-calendar-data.mjs', root),
  `// Generated by scripts/build-business-calendar.mjs from reviewed sheet 8, rows 6:310.\n`+
  `export const CALENDAR_SOURCE = Object.freeze(${JSON.stringify({asOf:'2037-06-30',from:data[0][0],through:data.at(-1)[0],sha256:sha})});\n`+
  `export const CALENDAR_ROWS = Object.freeze([\n${data.map(r=>'  Object.freeze('+JSON.stringify(r)+')').join(',\n')}\n]);\n`);
